export type KritaWebAgentActionPhase = "signal" | "safe-smoke" | "explicit-confirmation";
export type KritaWebAgentSideEffect = "none" | "local-state" | "krita-app" | "canvas-input";

export interface KritaWebAgentAction {
  tool: string;
  phase: KritaWebAgentActionPhase;
  sideEffect: KritaWebAgentSideEffect;
  requiresExplicitConfirmation: boolean;
  preconditions: readonly string[];
  purpose: string;
}

export interface KritaWebAgentSignal {
  protocol: "auvrynt.krita.web-agent/v1";
  request: "try-all";
  mode: "no-plugin-desktop";
  workspaceId: string;
  safety: {
    pluginRequired: false;
    pluginUsed: false;
    bridgeRequired: false;
    arbitraryCodeExecution: false;
    automaticMutation: false;
  };
  safeSmoke: {
    tools: readonly string[];
    order: readonly string[];
    conditionalSteps: readonly { tool: string; when: string }[];
  };
  explicitConfirmation: {
    tools: readonly string[];
    beforeEachTool: string;
    afterEachTool: string;
  };
  actions: readonly KritaWebAgentAction[];
  agentInstructions: readonly string[];
}

